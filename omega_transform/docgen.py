"""Generate the reference pages from the code, so they cannot drift.

``docs/configuration.md`` comes from the dataclasses in ``config.py``: names
and defaults from the classes, descriptions from each field's trailing comment
or the ``#:`` line above it. ``docs/cli.md`` comes from the argparse parser.
``tests/test_docs.py`` fails when a committed page differs from what this
module generates; ``omega docs`` rewrites them.
"""
from __future__ import annotations

import argparse
import inspect
import re
from dataclasses import MISSING, fields
from pathlib import Path

from . import config as C

HDR = ("<!-- Copyright (c) 2026 by C. Klukas -->\n"
       "<!-- SPDX-License-Identifier: GPL-3.0-only -->\n"
       "<!-- Generated by `omega docs` from {src}. Do not edit by hand. -->\n\n")

_FIELD = re.compile(r"^\s+(\w+):[^#]*?(?:#\s*(.*))?$")


def field_docs(cls) -> dict[str, str]:
    """Field name -> description, from the class source."""
    docs, pending = {}, ""
    for line in inspect.getsource(cls).splitlines():
        s = line.strip()
        if s.startswith("#:"):
            pending = (pending + " " + s[2:].strip()).strip()
            continue
        m = _FIELD.match(line)
        if m and not s.startswith(("def ", "@", "return", '"')):
            docs[m.group(1)] = (m.group(2) or pending or "").strip()
        pending = ""
    return docs


def _default(cls, f) -> str:
    if f.default is not MISSING:
        v = f.default
    elif f.default_factory is not MISSING:
        v = f.default_factory()
    else:
        return "required"
    if f.name == "python":
        return "the running interpreter"
    if isinstance(v, list) and v and hasattr(v[0], "__dataclass_fields__"):
        if all(hasattr(x, "name") for x in v) and cls is not C.EvaluatorConfig:
            return ", ".join(f"`{x.name}`" for x in v)
        return f"{len(v)} default entr{'y' if len(v) == 1 else 'ies'}"
    if v is None:
        return "none"
    if isinstance(v, bool):
        return "`true`" if v else "`false`"
    if isinstance(v, str):
        return f'`"{v}"`' if v else '`""`'
    if isinstance(v, list):
        return "`[" + ", ".join(f'"{x}"' for x in v) + "]`" if v else "`[]`"
    return f"`{v}`"


def _type(f) -> str:
    t = f.type if isinstance(f.type, str) else getattr(f.type, "__name__", str(f.type))
    t = t.replace("ModelSpec", "model").replace("Stage", "stage").replace("Feature", "feature")
    return t.replace("list[str]", "list of strings").replace(" | None", " or none")


SECTIONS = [
    ("[problem]", C.ProblemConfig, "What to optimize and how to describe it to the model.",
     {"evaluator", "llm", "search", "problem_dir"}),
    ("[evaluator]", C.EvaluatorConfig, "How candidates are built, run and scored.", set()),
    ("[[evaluator.stages]]", C.Stage, "One cascade stage; stages run in order.", set()),
    ("[llm]", C.LLMConfig, "The model server and models.", set()),
    ("[[llm.models]]", C.ModelSpec, "One model of the ensemble (a plain string sets only the name).",
     set()),
    ("[search]", C.SearchConfig, "The evolutionary search.", set()),
    ("[[search.features]]", C.Feature, "One MAP-Elites axis.", set()),
]


def configuration_page() -> str:
    out = [HDR.format(src="omega_transform/config.py"), "# Configuration\n\n",
           "A problem is configured by `omega.toml` in its directory. Every key except "
           "the required ones in `[problem]` has a default; unknown keys are an error. "
           "Paths are relative to the problem directory.\n"]
    for title, cls, intro, skip in SECTIONS:
        docs = field_docs(cls)
        out.append(f"\n## `{title}`\n\n{intro}\n\n| Key | Type | Default | Meaning |\n"
                   "|---|---|---|---|\n")
        for f in fields(cls):
            if f.name in skip:
                continue
            desc = docs.get(f.name, "").replace("|", "\\|")
            out.append(f"| `{f.name}` | {_type(f)} | {_default(cls, f)} | {desc} |\n")
    return "".join(out)


def cli_page(parser: argparse.ArgumentParser) -> str:
    out = [HDR.format(src="omega_transform/cli.py"), "# Command line\n\n",
           "`omega` (or `python3 -m omega_transform`) takes a command. Commands that "
           "inspect a run take its run directory; program ids may be abbreviated to a "
           "unique prefix.\n"]
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    for name, p in sub.choices.items():
        h = helps.get(name) or ""
        out.append(f"\n## `{name}`\n\n{h[:1].upper() + h[1:]}.\n\n")
        usage = p.format_usage().replace("usage: ", "").strip()
        usage = re.sub(r"\s+", " ", usage)
        out.append(f"```text\n{usage}\n```\n")
        rows = []
        for a in p._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            flag = ", ".join(a.option_strings) or a.dest
            if isinstance(a, argparse.BooleanOptionalAction):
                flag = " / ".join(a.option_strings)
            default = "" if a.default in (None, False, argparse.SUPPRESS) or \
                isinstance(a.default, bool) else f" Default: `{a.default}`."
            if isinstance(a.default, list):
                default = f" Default: `{' '.join(a.default)}`."
            text = (a.help or "").replace("|", "/").replace("<", "&lt;").replace(">", "&gt;")
            rows.append(f"| `{flag}` | {text}{default} |\n")
        if rows:
            out.append("\n| Argument | Meaning |\n|---|---|\n" + "".join(rows))
    return "".join(out)


CATEGORY_ORDER = ["Mathematical constructions", "Algorithms and heuristics",
                  "Performance (C++)", "Data and modelling", "Testing"]


def _paragraph(text: str) -> str:
    return " ".join(text.split())


def _paragraphs(text: str) -> str:
    """Blank-line separated paragraphs, each joined into one line."""
    return "\n\n".join(_paragraph(p) for p in re.split(r"\n\s*\n", text.strip()) if p.strip())


def examples_page(root: Path) -> str:
    """The example gallery, from every examples/*/omega.toml."""
    examples = _examples(root)
    out = [HDR.format(src="examples/*/omega.toml"), "# Examples\n\n",
           "Each example is a complete problem: a starting program with its editable "
           "region, an evaluator, and `omega.toml`. Run one with:\n\n"
           "```bash\npython3 -m omega_transform run examples/<name> --minutes 15\n```\n\n"
           "They double as the [model benchmark](benchmarking.md)'s workload and as "
           "templates for [your own problems](defining-problems.md). Each example's own "
           "page shows its starting program and, once benchmarked, the best result and "
           "how the model got there.\n\n"
           "| Example | Category | Language | Score |\n|---|---|---|---|\n"]
    for name, cat, cfg in examples:
        score = _paragraph(cfg.metrics_help).split(". ")[0].rstrip(".")
        out.append(f"| [{name}](examples/{name}.md) | {cat} | {cfg.lang_tag} | "
                   f"{score.replace('|', '/')} |\n")
    last = None
    for name, cat, cfg in examples:
        if cat != last:
            out.append(f"\n## {cat}\n")
            last = cat
        stages = ", ".join(s.name + (" (timed alone)" if s.exclusive else "")
                           for s in cfg.evaluator.stages)
        out.append(f"\n### {name}\n\n{_paragraph(cfg.description)}\n\n"
                   f"- **Score:** {_paragraph(cfg.metrics_help) or 'see the evaluator'}\n"
                   f"- **Language:** {cfg.lang_tag}; program `examples/{name}/{cfg.initial}`, "
                   f"evaluator stages: {stages}"
                   + ("; new bests are re-measured" if cfg.evaluator.confirm_runs else "")
                   + f"\n- **Details:** [starting program and best results](examples/{name}.md)\n")
    return "".join(out)


def _examples(root: Path) -> list[tuple[str, str, object]]:
    """(directory name, category, config) of every example, in gallery order."""
    from .config import load_config
    groups: dict[str, list] = {}
    for toml in sorted((root / "examples").glob("*/omega.toml")):
        cfg = load_config(toml)
        groups.setdefault(cfg.category or "Other", []).append((toml.parent.name, cfg))
    order = [c for c in CATEGORY_ORDER if c in groups] + sorted(set(groups) - set(CATEGORY_ORDER))
    return [(name, cat, cfg) for cat in order for name, cfg in groups[cat]]


PROVIDER_NAMES = {"openrouter": "OpenRouter", "ollama": "Ollama"}


def step_kind(mode: str) -> str:
    """What produced a program, from its search mode (e.g. "sweep/exploit/diff/refine")."""
    if mode == "initial":
        return "start"
    if mode.startswith("sweep/"):
        return "parameter sweep"
    if mode.startswith("retry/"):
        return "fix-up"
    return "rewrite" if "/rewrite/" in f"/{mode}/" else "edit"


def _fence(text: str) -> str:
    """A code fence long enough not to be closed by backticks inside ``text``."""
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def example_page(name: str, category: str, cfg, results: list[dict]) -> str:
    """One example: the problem, its starting program, and the best benchmark result
    with the path that led there."""
    from .prompt import fmt_score
    from .report import best_run, label, latest_per_model, shorten
    lang = "cpp" if cfg.language in ("cpp", "c++", "c") else cfg.language
    code = cfg.initial_path.read_text()
    stages = ", ".join(s.name + (" (timed alone)" if s.exclusive else "")
                       for s in cfg.evaluator.stages)
    out = [HDR.format(src=f"examples/{name}/ and bench/results/*.json"), f"# {name}\n\n",
           f"{category} · {cfg.lang_tag} · problem `{cfg.name}` · "
           "[all examples](../examples.md)\n\n",
           "## The problem\n\n", _paragraph(cfg.description), "\n\n",
           f"- **Score:** {_paragraph(cfg.metrics_help) or 'see the evaluator'}\n",
           f"- **Files:** `examples/{name}/omega.toml`, the program `{cfg.initial}`, "
           f"evaluator stages: {stages}"
           + ("; new bests are re-measured" if cfg.evaluator.confirm_runs else "") + "\n\n",
           f"### Why this is a hard problem\n\n{_paragraphs(cfg.background)}\n\n"
           if cfg.background.strip() else "",
           "Run it with:\n\n```bash\n"
           f"python3 -m omega_transform run examples/{name} --minutes 15\n```\n\n",
           "## The starting program\n\n"
           "The model may change only the code between the `OMEGA-BLOCK` markers.\n\n",
           f"{_fence(code)}{lang}\n{code.rstrip()}\n{_fence(code)}\n"]
    mine = [r for r in results if r.get("example") == cfg.name]
    out.append("\n## Benchmark results\n\n")
    if not mine:
        out.append("This example has not been benchmarked yet. See "
                   "[Benchmarking models](../benchmarking.md) for how to run it.\n")
        return "".join(out)
    best = best_run(mine, cfg.name)
    if best is not None:
        where = "locally with Ollama" if best.get("provider", "ollama") == "ollama" \
            else f"through {PROVIDER_NAMES.get(best['provider'], best['provider'])}"
        gain = f" (×{best['improvement']:.2f} the starting program's " \
               f"{fmt_score(best.get('initial_score'))})" if best.get("improvement") else ""
        mtb = best.get("minutes_to_best")
        out.append(
            f"The best result so far comes from **{label(best)}**, run {where} on "
            f"{best.get('started', '')[:10]}: a score of **{fmt_score(best['best_score'])}**"
            f"{gain}, reached after "
            + (f"{mtb:g} of {best.get('minutes_budget', 0):g} minutes" if mtb is not None
               else "no improvement")
            + f" with {best.get('llm_calls', 0)} model requests.\n")
        if _figure_panels(best):
            out.append(_figure_text(name, best))
        steps = best.get("best_lineage") or []
        if len(steps) > 1:
            out.append("\n### How it got there\n\n"
                       "The best program's ancestry, from the starting program on. "
                       "\"Edit\" and \"rewrite\" are the model's changes; a parameter sweep "
                       "is the engine trying values for the constants the model exposed.\n\n"
                       "| Step | Minute | Score | Kind | Idea |\n|--:|--:|--:|---|---|\n")
            for i, s in enumerate(steps):
                idea = shorten(s.get("idea") or "", 260).replace("|", "/")
                score = fmt_score(s.get("score")) if s.get("score") is not None else \
                    (s.get("status") or "-").replace("_", " ")
                out.append(f"| {i} | {s.get('minutes', 0):.1f} | {score} "
                           f"| {step_kind(s.get('mode', ''))} | {idea} |\n")
        diff = best.get("best_diff") or ""
        if diff:
            out.append("\n### The best program\n\nWhat changed compared with the starting "
                       "program:\n\n" f"{_fence(diff)}diff\n{diff.rstrip()}\n{_fence(diff)}\n")
        elif len(steps) == 1:
            out.append("\nNo model improved on the starting program.\n")
        elif not steps:
            out.append("\nThe path to this result was not recorded (its run predates it).\n")
    rows = sorted(latest_per_model(mine).get(cfg.name, {}).values(),
                  key=lambda r: -(r.get("best_score") if r.get("best_score") is not None
                                  else float("-inf")))
    out.append("\n### All models\n\nThe latest run per model and reasoning mode; the "
               f"[model benchmarks](../benchmarks/{cfg.name}.md) page has speed, memory and "
               "progress over time.\n\n"
               "| Model | Where | Best | Gain | Minutes to best | New bests |\n"
               "|---|---|--:|--:|--:|--:|\n")
    for r in rows:
        where = "local" if r.get("provider", "ollama") == "ollama" else "cloud"
        if r.get("error"):
            out.append(f"| {label(r)} | {where} | | | | failed: "
                       f"{shorten(r['error'], 60).replace('|', '/')} |\n")
            continue
        gain = f"×{r['improvement']:.2f}" if r.get("improvement") else "-"
        mtb = r.get("minutes_to_best")
        out.append(f"| {label(r)} | {where} | {fmt_score(r.get('best_score'))} | {gain} | "
                   f"{'-' if mtb is None else f'{mtb:.1f}'} | {r.get('improvements', 0)} |\n")
    return "".join(out)


def _figure_panels(best: dict) -> list[tuple[str, dict, float | None]]:
    """The panels of an example's figure: the starting program's solution and, when
    the best program improved on it, the best one's."""
    from .figures import drawable
    from .prompt import fmt_score
    panels = []
    if drawable(best.get("initial_solution")):
        panels.append((f"Starting program · score {fmt_score(best.get('initial_score'))}",
                       best["initial_solution"], best.get("initial_score")))
    if best.get("best_diff") and drawable(best.get("best_solution")):
        panels.append((f"Best · score {fmt_score(best['best_score'])}", best["best_solution"],
                       best["best_score"]))
    return panels


def _figure_text(name: str, best: dict) -> str:
    from .report import label
    panels = _figure_panels(best)
    instance = panels[0][1].get("instance")
    what = "What the starting program produces (left) and what the best program " \
        f"by {label(best)} produces (right)" if len(panels) == 2 else \
        ("What the best program produces" if panels[0][0].startswith("Best") else
         "What the starting program produces; no model improved on it")
    if instance:
        what += f", drawn for the instance `{instance}`"
    alt = f"{name}: the starting program's solution" + \
        (" and the best one" if len(panels) == 2 else "")
    return f"\n{what}:\n\n![{alt}](../assets/examples/{name}.svg)\n"


def figures(results: list[dict], examples) -> dict[str, str]:
    """docs/assets/examples/<name>.svg for every example whose best result carries
    drawable solutions."""
    from .figures import figure
    from .report import best_run
    out = {}
    for name, _, cfg in examples:
        best = best_run(results, cfg.name)
        panels = _figure_panels(best) if best else []
        if panels:
            out[f"docs/assets/examples/{name}.svg"] = figure(
                panels, f"{name}: the starting program's solution and the best one")
    return out


GALLERY_START = "<!-- examples-gallery:start (generated by `omega docs`) -->"
GALLERY_END = "<!-- examples-gallery:end -->"
GALLERY_COLUMNS = 3


def start_page(text: str, results: list[dict], examples, figures: dict[str, str]) -> str:
    """docs/index.md with its generated block renewed: the benchmark status and a grid of
    every example's figure, each linking to the example's page."""
    if GALLERY_START not in text or GALLERY_END not in text:
        return text
    from .report import label
    ok = [r for r in results if not r.get("error") and r.get("best_score") is not None]
    names = {cfg.name for _, cat, cfg in examples if cat != "Testing"}
    shown = [(name, cfg) for name, cat, cfg in examples if cat != "Testing"]
    improved = {r["example"] for r in ok if (r.get("improvement") or 0) > 1}
    block = [GALLERY_START, "",
             f"The benchmark so far: {len({label(r) for r in ok}):,} models and reasoning "
             f"modes in {len(ok):,} runs on the {len(names)} examples; on "
             f"{len(improved & names)} of them a model improved on the starting program. "
             "Each picture shows what the starting program and the best program found so "
             "far produce; click one for the problem, the path to the best result and "
             "all models.", ""]
    cells = []
    for name, cfg in shown:
        summary = _paragraph(cfg.summary) or _paragraph(cfg.description).split(". ")[0]
        tip = summary.replace('"', "'")
        link = f"examples/{name}.md"
        pic = (f'[![{name}](assets/examples/{name}.svg "{tip}")]({link})<br>'
               if f"docs/assets/examples/{name}.svg" in figures else "")
        cells.append(f"{pic}**[{name}]({link})**<br><small>{summary.replace('|', '/')}</small>")
    while len(cells) % GALLERY_COLUMNS:
        cells.append(" ")
    block.append("|" + " |" * GALLERY_COLUMNS)
    block.append("|" + "---|" * GALLERY_COLUMNS)
    for k in range(0, len(cells), GALLERY_COLUMNS):
        block.append("| " + " | ".join(cells[k:k + GALLERY_COLUMNS]) + " |")
    block += ["", GALLERY_END]
    head, rest = text.split(GALLERY_START, 1)
    return head + "\n".join(block) + rest.split(GALLERY_END, 1)[1]


def pages() -> dict[str, str]:
    from .cli import build_parser
    root = Path(__file__).resolve().parent.parent
    from .report import load_results
    out = {"docs/configuration.md": configuration_page(), "docs/cli.md": cli_page(build_parser()),
           "docs/examples.md": examples_page(root)}
    results = load_results(root / "bench" / "results")
    examples = _examples(root)
    for name, cat, cfg in examples:
        out[f"docs/examples/{name}.md"] = example_page(name, cat, cfg, results)
    figs = figures(results, examples)
    out.update(figs)
    out["docs/index.md"] = start_page((root / "docs" / "index.md").read_text(), results,
                                      examples, figs)
    return out


def write_pages(root: Path) -> list[Path]:
    written = []
    for rel, text in pages().items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        written.append(p)
    return written
