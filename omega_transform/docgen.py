"""Generate the reference pages from the code, so they cannot drift.

``docs/configuration.md`` comes from the dataclasses in ``config.py``: names
and defaults from the classes, descriptions from each field's trailing comment
or the ``#:`` line above it. ``docs/cli.md`` comes from the argparse parser.
``tests/test_docs.py`` fails when a committed page differs from what this
module generates; ``omega docs`` rewrites them.
"""
from __future__ import annotations

import argparse
import inspect
import re
from dataclasses import MISSING, fields
from pathlib import Path

from . import config as C

HDR = ("<!-- Copyright (c) 2026 by C. Klukas -->\n"
       "<!-- SPDX-License-Identifier: GPL-3.0-only -->\n"
       "<!-- Generated by `omega docs` from {src}. Do not edit by hand. -->\n\n")

_FIELD = re.compile(r"^\s+(\w+):[^#]*?(?:#\s*(.*))?$")


def field_docs(cls) -> dict[str, str]:
    """Field name -> description, from the class source."""
    docs, pending = {}, ""
    for line in inspect.getsource(cls).splitlines():
        s = line.strip()
        if s.startswith("#:"):
            pending = (pending + " " + s[2:].strip()).strip()
            continue
        m = _FIELD.match(line)
        if m and not s.startswith(("def ", "@", "return", '"')):
            docs[m.group(1)] = (m.group(2) or pending or "").strip()
        pending = ""
    return docs


def _default(cls, f) -> str:
    if f.default is not MISSING:
        v = f.default
    elif f.default_factory is not MISSING:
        v = f.default_factory()
    else:
        return "required"
    if f.name == "python":
        return "the running interpreter"
    if isinstance(v, list) and v and hasattr(v[0], "__dataclass_fields__"):
        if all(hasattr(x, "name") for x in v) and cls is not C.EvaluatorConfig:
            return ", ".join(f"`{x.name}`" for x in v)
        return f"{len(v)} default entr{'y' if len(v) == 1 else 'ies'}"
    if v is None:
        return "none"
    if isinstance(v, bool):
        return "`true`" if v else "`false`"
    if isinstance(v, str):
        return f'`"{v}"`' if v else '`""`'
    if isinstance(v, list):
        return "`[" + ", ".join(f'"{x}"' for x in v) + "]`" if v else "`[]`"
    return f"`{v}`"


def _type(f) -> str:
    t = f.type if isinstance(f.type, str) else getattr(f.type, "__name__", str(f.type))
    t = t.replace("ModelSpec", "model").replace("Stage", "stage").replace("Feature", "feature")
    return t.replace("list[str]", "list of strings").replace(" | None", " or none")


SECTIONS = [
    ("[problem]", C.ProblemConfig, "What to optimize and how to describe it to the model.",
     {"evaluator", "llm", "search", "problem_dir"}),
    ("[evaluator]", C.EvaluatorConfig, "How candidates are built, run and scored.", set()),
    ("[[evaluator.stages]]", C.Stage, "One cascade stage; stages run in order.", set()),
    ("[llm]", C.LLMConfig, "The model server and models.", set()),
    ("[[llm.models]]", C.ModelSpec, "One model of the ensemble (a plain string sets only the name).",
     set()),
    ("[search]", C.SearchConfig, "The evolutionary search.", set()),
    ("[[search.features]]", C.Feature, "One MAP-Elites axis.", set()),
]


def configuration_page() -> str:
    out = [HDR.format(src="omega_transform/config.py"), "# Configuration\n\n",
           "A problem is configured by `omega.toml` in its directory. Every key except "
           "the required ones in `[problem]` has a default; unknown keys are an error. "
           "Paths are relative to the problem directory.\n"]
    for title, cls, intro, skip in SECTIONS:
        docs = field_docs(cls)
        out.append(f"\n## `{title}`\n\n{intro}\n\n| Key | Type | Default | Meaning |\n"
                   "|---|---|---|---|\n")
        for f in fields(cls):
            if f.name in skip:
                continue
            desc = docs.get(f.name, "").replace("|", "\\|")
            out.append(f"| `{f.name}` | {_type(f)} | {_default(cls, f)} | {desc} |\n")
    return "".join(out)


def cli_page(parser: argparse.ArgumentParser) -> str:
    out = [HDR.format(src="omega_transform/cli.py"), "# Command line\n\n",
           "`omega` (or `python3 -m omega_transform`) takes a command. Commands that "
           "inspect a run take its run directory; program ids may be abbreviated to a "
           "unique prefix.\n"]
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    for name, p in sub.choices.items():
        h = helps.get(name) or ""
        out.append(f"\n## `{name}`\n\n{h[:1].upper() + h[1:]}.\n\n")
        usage = p.format_usage().replace("usage: ", "").strip()
        usage = re.sub(r"\s+", " ", usage)
        out.append(f"```text\n{usage}\n```\n")
        rows = []
        for a in p._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            flag = ", ".join(a.option_strings) or a.dest
            if isinstance(a, argparse.BooleanOptionalAction):
                flag = " / ".join(a.option_strings)
            default = "" if a.default in (None, False, argparse.SUPPRESS) or \
                isinstance(a.default, bool) else f" Default: `{a.default}`."
            if isinstance(a.default, list):
                default = f" Default: `{' '.join(a.default)}`."
            text = (a.help or "").replace("|", "/").replace("<", "&lt;").replace(">", "&gt;")
            rows.append(f"| `{flag}` | {text}{default} |\n")
        if rows:
            out.append("\n| Argument | Meaning |\n|---|---|\n" + "".join(rows))
    return "".join(out)


CATEGORY_ORDER = ["Mathematical constructions", "Algorithms and heuristics",
                  "Performance (C++)", "Data and modelling", "Testing"]


def _paragraph(text: str) -> str:
    return " ".join(text.split())


def examples_page(root: Path) -> str:
    """The example gallery, from every examples/*/omega.toml."""
    from .config import load_config
    groups: dict[str, list] = {}
    for toml in sorted((root / "examples").glob("*/omega.toml")):
        cfg = load_config(toml)
        groups.setdefault(cfg.category or "Other", []).append((toml.parent.name, cfg))
    order = [c for c in CATEGORY_ORDER if c in groups] + sorted(set(groups) - set(CATEGORY_ORDER))
    out = [HDR.format(src="examples/*/omega.toml"), "# Examples\n\n",
           "Each example is a complete problem: a starting program with its editable "
           "region, an evaluator, and `omega.toml`. Run one with:\n\n"
           "```bash\npython3 -m omega_transform run examples/<name> --minutes 15\n```\n\n"
           "They double as the [model benchmark](benchmarking.md)'s workload and as "
           "templates for [your own problems](defining-problems.md).\n\n"
           "| Example | Category | Language | Score |\n|---|---|---|---|\n"]
    for cat in order:
        for name, cfg in groups[cat]:
            score = _paragraph(cfg.metrics_help).split(". ")[0].rstrip(".")
            out.append(f"| [{name}](#{name}) | {cat} | {cfg.lang_tag} | "
                       f"{score.replace('|', '/')} |\n")
    for cat in order:
        out.append(f"\n## {cat}\n")
        for name, cfg in groups[cat]:
            stages = ", ".join(s.name + (" (timed alone)" if s.exclusive else "")
                               for s in cfg.evaluator.stages)
            out.append(f"\n### {name}\n\n{_paragraph(cfg.description)}\n\n"
                       f"- **Score:** {_paragraph(cfg.metrics_help) or 'see the evaluator'}\n"
                       f"- **Language:** {cfg.lang_tag}; program `examples/{name}/{cfg.initial}`, "
                       f"evaluator stages: {stages}"
                       + ("; new bests are re-measured" if cfg.evaluator.confirm_runs else "")
                       + "\n")
    return "".join(out)


def pages() -> dict[str, str]:
    from .cli import build_parser
    root = Path(__file__).resolve().parent.parent
    return {"docs/configuration.md": configuration_page(), "docs/cli.md": cli_page(build_parser()),
            "docs/examples.md": examples_page(root)}


def write_pages(root: Path) -> list[Path]:
    written = []
    for rel, text in pages().items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        written.append(p)
    return written
