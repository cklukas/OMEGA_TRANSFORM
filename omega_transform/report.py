"""Render committed benchmark results into a documentation page.

Input: ``bench/results/*.json`` written by ``omega bench``. Output: one
Markdown page with tables and Mermaid ``xychart-beta`` charts, which ckdocs
renders to SVG. The page is regenerated in CI before the site is built, so
the published charts always match the committed numbers.
"""
from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

from .prompt import fmt_score

HEADER = """<!-- Copyright (c) 2026 by C. Klukas -->
<!-- SPDX-License-Identifier: GPL-3.0-only -->
<!-- Generated by `omega report` from bench/results/*.json. Do not edit by hand. -->

# Model benchmarks

Each row is one time-boxed OMEGA TRANSFORM search: the same example, the same
budget and the same settings, with only the Ollama model changed. The numbers
come from the committed result files in `bench/results/`; rerun
`omega bench` to add new ones (see [Benchmarking models](benchmarking.md)).

Read the results with care: one run per model is a single sample of a
stochastic search, and timing-based scores (the C++ example) depend on what
else the machine was doing.
"""


def load_results(results_dir: Path) -> list[dict]:
    out = []
    for p in sorted(results_dir.glob("*.json")):
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        d["_file"] = p.name
        out.append(d)
    return out


def label(r: dict) -> str:
    """Model name plus its reasoning mode when that was set explicitly."""
    v = r.get("variant", "default")
    return r["model"] if v == "default" else f"{r['model']} ({v})"


def chart_label(r: dict) -> str:
    """Short label for chart axes: no vendor prefix, no ":free"/":latest" tag."""
    name = r["model"].split("/")[-1]
    for tag in (":free", ":latest"):
        name = name.removesuffix(tag)
    v = r.get("variant", "default")
    return name if v == "default" else f"{name} ({v})"


def shorten(text: str, n: int = 180) -> str:
    text = " ".join(text.split())
    if len(text) <= n:
        return text
    cut = text[:n].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + " …"


def latest_per_model(results: list[dict]) -> dict[str, dict[str, dict]]:
    """{example: {model and variant: newest result}}"""
    table: dict[str, dict[str, dict]] = defaultdict(dict)
    for r in sorted(results, key=lambda r: r.get("started", "")):
        table[r["example"]][label(r)] = r
    return table


def _q(label: str) -> str:
    return '"' + label.replace('"', "'") + '"'


def bar_chart(title: str, labels: list[str], values: list[float], y_label: str) -> str:
    top = max([v for v in values if v is not None] or [1.0])
    vals = ", ".join(f"{(v or 0):.4g}" for v in values)
    return (f"```mermaid\nxychart-beta\n    title {_q(title)}\n"
            f"    x-axis [{', '.join(_q(lbl) for lbl in labels)}]\n"
            f"    y-axis {_q(y_label)} 0 --> {top * 1.1:.4g}\n    bar [{vals}]\n```\n")


def score_at(progress: list, minute: float) -> float | None:
    best = None
    for t, s in progress or []:
        if t <= minute:
            best = s
    return best


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.0f}%" if b else "-"


def _num(v, fmt: str = "{:.1f}") -> str:
    return "-" if v is None else fmt.format(v)


def inference_section(example: str, rows: list[dict], level: str = "###",
                      local: bool = True) -> str:
    """How fast each model is and how much memory it takes, on this example's prompts."""
    rows = [r for r in rows if r.get("gen_tokens_per_s") is not None
            or r.get("model_memory_gb") is not None]
    if not rows:
        return ""
    rows = sorted(rows, key=lambda r: r.get("model_memory_gb") or 0)
    if not local:
        return cloud_inference_section(example, rows, level)
    out = [f"\n{level} Inference speed and memory\n\n"
           "RAM is what Ollama reports for the loaded model (weights, context cache and "
           "buffers; on Apple silicon this is shared memory). Load is the time to bring "
           "the model into memory. Prompt and generation speeds are tokens per second over "
           "all calls of the run.\n\n"
           "| Model | Params | RAM GB | Load s | Prompt tok/s | Gen tok/s | Median s/call "
           "| p90 s/call | Tokens/answer | Stopped |\n"
           "|---|---|--:|--:|--:|--:|--:|--:|--:|--:|\n"]
    for r in rows:
        out.append(
            f"| {label(r)} | {r.get('model_params', '')} | {_num(r.get('model_memory_gb'))} "
            f"| {_num(r.get('load_seconds'), '{:.0f}')} | {_num(r.get('prompt_tokens_per_s'), '{:.0f}')} "
            f"| {_num(r.get('gen_tokens_per_s'))} | {_num(r.get('median_call_seconds'), '{:.0f}')} "
            f"| {_num(r.get('p90_call_seconds'), '{:.0f}')} | {_num(r.get('mean_gen_tokens'), '{:.0f}')} "
            f"| {r.get('stopped_calls', 0)} |\n")
    labels = [chart_label(r) for r in rows]
    if any(r.get("gen_tokens_per_s") for r in rows):
        out.append("\n" + bar_chart(f"{example}: generation speed (tokens/s)", labels,
                                     [r.get("gen_tokens_per_s") for r in rows], "tokens/s"))
    if any(r.get("model_memory_gb") for r in rows):
        out.append("\n" + bar_chart(f"{example}: model memory (GB)", labels,
                                     [r.get("model_memory_gb") for r in rows], "GB"))
    return "".join(out)


def check_section(check: dict) -> str:
    """Which installed models were found usable before the benchmark, and why not."""
    models = check.get("models") or []
    if not models:
        return ""
    out = [f"\n## Model check\n\nBefore benchmarking, `omega models` loads every installed "
           f"model, greets it, asks for a three-line edit in the engine's SEARCH/REPLACE format, "
           f"and tries its reasoning mode. Only models marked ok are benchmarked. Checked "
           f"{check.get('checked', '')[:10]}.\n\n"
           "| Model | Params | Size GB | Verdict | Load s | Gen tok/s | RAM GB | Hello | Edit "
           "| Think | Note |\n|---|---|--:|---|--:|--:|--:|---|---|---|---|\n"]

    def yn(v):
        return "-" if v is None else ("yes" if v else "no")
    for m in sorted(models, key=lambda m: m.get("size_gb") or 0):
        out.append(f"| {m['model']} | {m.get('params', '')} | {m.get('size_gb', '')} "
                   f"| {m.get('verdict', '')} | {_num(m.get('load_seconds'), '{:.0f}')} "
                   f"| {_num(m.get('gen_tokens_per_s'))} | {_num(m.get('memory_gb'))} "
                   f"| {yn(m.get('hello_ok'))} | {yn(m.get('edit_ok'))} | {yn(m.get('think_ok'))} "
                   f"| {(m.get('reason') or '').replace('|', '/')[:80]} |\n")
    return "".join(out)


def cloud_inference_section(example: str, rows: list[dict], level: str) -> str:
    """Speed and cost of cloud models; they use no local memory and need no loading."""
    rows = sorted(rows, key=lambda r: -(r.get("gen_tokens_per_s") or 0))
    out = [f"\n{level} Inference speed and cost\n\n"
           "Generation speed is measured from the first to the last streamed token; the "
           "time to the first token is counted as prompt time. Cost is what OpenRouter "
           "charged for the run.\n\n"
           "| Model | Gen tok/s | Median s/call | p90 s/call | Tokens/answer | Stopped "
           "| Cost $ |\n|---|--:|--:|--:|--:|--:|--:|\n"]
    for r in rows:
        out.append(f"| {label(r)} | {_num(r.get('gen_tokens_per_s'))} "
                   f"| {_num(r.get('median_call_seconds'), '{:.0f}')} "
                   f"| {_num(r.get('p90_call_seconds'), '{:.0f}')} "
                   f"| {_num(r.get('mean_gen_tokens'), '{:.0f}')} | {r.get('stopped_calls', 0)} "
                   f"| {r.get('cost_usd') or 0:.3f} |\n")
    if any(r.get("gen_tokens_per_s") for r in rows):
        out.append("\n" + bar_chart(f"{example}: generation speed (tokens/s)",
                                     [chart_label(r) for r in rows],
                                     [r.get("gen_tokens_per_s") for r in rows], "tokens/s"))
    return "".join(out)


